import {chromium} from '@playwright/test';
const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',headless:true,args:['--no-sandbox']});
try {
 const page=await browser.newPage({viewport:{width:1366,height:768}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:3000');
 await page.waitForFunction(()=>!document.querySelector('.play-button')?.disabled);
 if(!await page.title().then(t=>t.includes('Watt a Beat')))throw new Error('Title not updated');
 await page.getByRole('button',{name:'Christmas A little holiday magic'}).click();
 const snow=page.getByTestId('snowfall');
 if(await snow.locator('path').count()!==120||await snow.locator('circle').count())throw new Error('Crystalline snowflake shapes missing');
 const before=await snow.locator('path').nth(1).getAttribute('transform');
 await page.getByRole('button',{name:'Play',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('.timecode')?.textContent?.startsWith('00:02'));
 await page.getByRole('button',{name:'Pause',exact:true}).click();
 if(before===await snow.locator('path').nth(1).getAttribute('transform'))throw new Error('Snow did not fall');
 await page.getByRole('button',{name:'Cut all power',exact:true}).click();
 if(!await page.locator('[data-district]').evaluateAll(nodes=>nodes.every(n=>n.getAttribute('data-power')==='0.000')))throw new Error('Brownout did not disconnect all districts');
 await page.getByRole('button',{name:'Reconnect all',exact:true}).click();
 if(!await page.locator('[data-district]').evaluateAll(nodes=>nodes.some(n=>Number(n.getAttribute('data-power'))>0)))throw new Error('Reconnect did not restore music response');
 await page.getByRole('switch',{name:'Snowfall'}).click();
 if(await snow.count())throw new Error('Snow toggle failed');
 await page.getByRole('switch',{name:'Snowfall'}).click();
 await page.screenshot({path:'/tmp/brownout-beats-desktop.png',fullPage:true});
 const desktopLayout=await page.evaluate(()=>({page:document.documentElement.scrollHeight,viewport:innerHeight,panel:document.querySelector('.sidebar').scrollHeight,panelHeight:document.querySelector('.sidebar').clientHeight}));
 console.log('Desktop layout:',desktopLayout);
 if(desktopLayout.page>desktopLayout.viewport||desktopLayout.panel>desktopLayout.panelHeight+1)throw new Error('Desktop studio still scrolls');
 await page.getByRole('button',{name:'Rain Rain over the city'}).click();
 const rain = page.getByTestId('rainfall');
 if(await rain.locator('line').count()!==160 || await snow.count())throw new Error('Rain theme did not replace snow');
 const rainBefore = await rain.locator('line').first().getAttribute('y1');
 await page.getByRole('button',{name:'Play',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('.timecode')?.textContent?.startsWith('00:04'));
 await page.getByRole('button',{name:'Pause',exact:true}).click();
 if(rainBefore===await rain.locator('line').first().getAttribute('y1'))throw new Error('Rain is static');
 await page.getByRole('switch',{name:'Rainfall'}).click();
 if(await rain.count())throw new Error('Rain toggle failed');
 await page.getByRole('switch',{name:'Rainfall'}).click();
 await page.screenshot({path:'/tmp/brownout-beats-rain-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'/tmp/brownout-beats-mobile.png',fullPage:true});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('Mobile overflow');
 await page.getByRole('tab',{name:'Effects',exact:true}).click();
 await page.getByRole('switch',{name:'Rainfall'}).waitFor();
 await page.getByRole('tab',{name:'District power',exact:true}).click();
 await page.getByRole('button',{name:'Cut all power',exact:true}).click();
 await page.getByRole('button',{name:'Reconnect all',exact:true}).click();
 await page.getByRole('tab',{name:'Atmosphere',exact:true}).click();
 await page.getByRole('button',{name:'Export video'}).click();
 await page.getByLabel('Resolution',{exact:true}).selectOption('720');
 await page.getByLabel('Duration',{exact:true}).selectOption('10');
 const responsePromise=page.waitForResponse(r=>r.url().endsWith('/api/exports')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Render video',exact:true}).click();
 const res=await responsePromise,job=await res.json();
 if(!res.ok())throw new Error(JSON.stringify(job));
 console.log('Rain brownout export:',job.id);
 await page.getByRole('link',{name:'Download video'}).waitFor({timeout:180000});
 if(errors.length)throw new Error(errors.join('\n'));
 console.log('Compact layout, crystalline snow, rain animation, weather toggles, district power, mobile tabs, and rain MP4 export passed.');
}finally{await browser.close();}
